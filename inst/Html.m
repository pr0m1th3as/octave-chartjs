classdef Html
## -*- texinfo -*-
## @deftypefn  {chartjs} {@var{obj} =} html ()
##
## A parent class for generating HMTL code.
##
## Do NOT use this class directly! This class acts as a parent class for
## inheriting methods to the Chart classes for generating HTML code.
##
## To view a Chart object in your web browser, use its @qcode{webserve}
## method.
##
## @seealso{BarChart, BubbleChart, DoughnutChart, LineChart, PieChart,
## PolarAreaChart, RadarChart, ScatterChart}
## @end deftypefn

  methods (Access = private)

    ## Void Constructor
    function this = html ()

    endfunction

  endmethods

  methods (Access = public)

    ## -*- texinfo -*-
    ## @deftypefn  {chartjs} {@var{json} =} jsonstring (@var{obj})
    ##
    ## Generate the JSON string of a Chart object.
    ##
    ## @code{jsonstring (@var{obj})} returns a character vector, @var{json},
    ## holding the Chart.js configuration of a Chart object in JSON.
    ##
    ## @seealso{BarChart, BubbleChart, DoughnutChart, LineChart, PieChart,
    ## PolarAreaChart, RadarChart, ScatterChart}
    ## @end deftypefn

    function json = jsonstring (obj)

      json = __chartjson__ (jsonvalue (obj), jsonpaths ('chart'));

    endfunction

    ## -*- texinfo -*-
    ## @deftypefn  {chartjs} {@var{html} =} htmlstring (@var{obj})
    ## @deftypefnx {chartjs} {@var{html} =} htmlstring (@var{obj}, @var{source})
    ##
    ## Generate an HTML string from a Chart object.
    ##
    ## @code{htmlstring (@var{obj})} returns a character vector defining the
    ## HTML code to display a Chart object on a web browser.  Use the
    ## @qcode{webserve} method to view it in your web browser.
    ##
    ## @code{htmlstring (@var{obj}, @var{source})} also sets where the page
    ## loads the Chart.js library from, as one of the following.
    ##
    ## @multitable @columnfractions 0.15 0.02 0.83
    ## @headitem @var{source} @tab @tab Chart.js is loaded
    ## @item @qcode{"inline"} @tab @tab from a copy written into the page, the
    ## default.  The page opens without a network connection and never changes.
    ## @item @qcode{"cdn"} @tab @tab from the jsDelivr CDN, pinned to the
    ## release bundled with the package and checked against its hash, so that
    ## the browser runs nothing else.
    ## @item a URL @tab @tab from @var{source}, such as
    ## @qcode{"/static/chart.umd.min.js"} on a server that hosts the file.  A
    ## URL holds a @qcode{/} or ends in @qcode{.js}.
    ## @end multitable
    ##
    ## @seealso{BarChart, BubbleChart, DoughnutChart, LineChart, PieChart,
    ## PolarAreaChart, RadarChart, ScatterChart}
    ## @end deftypefn

    function html = htmlstring (obj, source)

      if (nargin < 2)
        source = "inline";
      endif
      [tag, errmsg] = script_element (source);
      if (! isempty (errmsg))
        error ("%s.htmlstring: %s", class (obj), errmsg);
      endif
      html = chart_page (obj, tag);

    endfunction

    ## -*- texinfo -*-
    ## @deftypefn  {chartjs} {} htmlsave (@var{obj}, @var{filename})
    ## @deftypefnx {chartjs} {} htmlsave (@var{obj}, @var{filename}, @var{source})
    ##
    ## Save a Chart object's HTML code to a file.
    ##
    ## @code{htmlsave (@var{obj}, @var{filename})} saves the HTML code
    ## describing a Chart object to a file.  The HTML code is identical to that
    ## generated by the @code{htmlstring} method, and @var{source} sets where
    ## it loads Chart.js from in the same way.
    ##
    ## @seealso{BarChart, BubbleChart, DoughnutChart, LineChart, PieChart,
    ## PolarAreaChart, RadarChart, ScatterChart}
    ## @end deftypefn

    function htmlsave (obj, filename, source)

      ## Check filename
      if (nargin < 2)
        error ("%s.htmlsave: too few input arguments.", class (obj));
      elseif (! ischar (filename))
        error ("%s.htmlsave: FILENAME must be a character vector.", class (obj));
      endif
      if (nargin < 3)
        source = "inline";
      endif
      [tag, errmsg] = script_element (source);
      if (! isempty (errmsg))
        error ("%s.htmlsave: %s", class (obj), errmsg);
      endif

      ## Write html string to file
      fid = fopen (filename, "w");
      fprintf (fid, "%s", chart_page (obj, tag));
      fclose (fid);

    endfunction

    ## -*- texinfo -*-
    ## @deftypefn  {chartjs} {} webserve (@var{obj})
    ## @deftypefnx {chartjs} {} webserve (@var{obj}, @var{filename})
    ## @deftypefnx {chartjs} {} webserve (@var{obj}, @var{filename}, @var{source})
    ##
    ## View a Chart object in your web browser.
    ##
    ## @code{webserve (@var{obj})} saves the HTML code describing the Chart
    ## object to a temporary file and opens it in your system's web browser.
    ## No web server is involved: the page is opened from the file.
    ##
    ## @code{webserve (@var{obj}, @var{filename})} saves the HTML code to
    ## @var{filename} instead, so that the page can be kept and opened again.
    ## Calling it again with the same @var{filename} and reloading the page in
    ## the browser shows the updated chart.  An empty @var{filename} uses a
    ## temporary file.
    ##
    ## @code{webserve (@var{obj}, @var{filename}, @var{source})} sets where the
    ## page loads Chart.js from, as in @code{htmlstring}.
    ##
    ## @seealso{BarChart, BubbleChart, DoughnutChart, LineChart, PieChart,
    ## PolarAreaChart, RadarChart, ScatterChart}
    ## @end deftypefn

    function webserve (this, filename, source)

      ## Check filename
      if (nargin < 2 || isempty (filename))
        filename = [tempname(), ".html"];
      elseif (! (ischar (filename) && isrow (filename)))
        error ("%s.webserve: FILENAME must be a character vector.", ...
               class (this));
      endif
      if (nargin < 3)
        source = "inline";
      endif
      [~, errmsg] = script_element (source);
      if (! isempty (errmsg))
        error ("%s.webserve: %s", class (this), errmsg);
      endif

      ## Save the page and open it with the system's web browser
      htmlsave (this, filename, source);
      web (make_absolute_filename (filename));

    endfunction

  endmethods

endclassdef

## The Chart.js release bundled with the package: its version, the file under
## inst/js, and the hash that pins the same file on the CDN
function [version, file, integrity] = bundled_chartjs ()
  version = "4.5.1";
  file = fullfile (fileparts (mfilename ("fullpath")), "js", ...
                   "chart.umd.min.js");
  integrity = ["sha384-jb8JQMbMoBUzgWatfe6COACi2ljcDdZQ2", ...
               "OxczGA3bGNeWe+6DChMTBJemed7ZnvJ"];
endfunction

## The <script> element loading Chart.js from SOURCE, or an error message
function [tag, errmsg] = script_element (source)
  tag = "";
  errmsg = "";
  [version, file, integrity] = bundled_chartjs ();
  if (! (ischar (source) && isrow (source)))
    errmsg = "SOURCE must be 'inline', 'cdn', or a URL.";
  elseif (strcmp (source, "inline"))
    tag = ["  <script>\n", fileread(file), "\n  </script>\n"];
  elseif (strcmp (source, "cdn"))
    url = ["https://cdn.jsdelivr.net/npm/chart.js@", version, ...
           "/dist/chart.umd.min.js"];
    tag = sprintf (["  <script src=\"%s\" integrity=\"%s\"", ...
                    " crossorigin=\"anonymous\"></script>\n"], url, integrity);
  elseif (any (source == "/") || endsWith (source, ".js"))
    tag = sprintf ("  <script src=\"%s\"></script>\n", attribute (source));
  else
    errmsg = "SOURCE must be 'inline', 'cdn', or a URL.";
  endif
endfunction

## Text escaped for an HTML attribute value
function str = attribute (str)
  str = strrep (str, "&", "&amp;");
  str = strrep (strrep (str, "\"", "&quot;"), "'", "&#39;");
  str = strrep (strrep (str, "<", "&lt;"), ">", "&gt;");
endfunction

## The page showing the chart, loading Chart.js through TAG
function html = chart_page (obj, tag)
  ## Initialize html string
  tmp1 = "<!DOCTYPE html>\n<html>\n";
  tmp3 = "  <body>\n    <div>\n";
  ## Add chart ID, escaped for an HTML attribute
  tmp4 = sprintf ("    <canvas id=\"%s\" style=\"width:100%%\">", ...
                  attribute (obj.chartID));
  tmp5 = "</canvas>\n    </div>\n  </body>\n</html>\n";
  tmp6 = "<script>\n";
  ## The JSON writes every '<' as an escape, so no string closes the script
  tmp7 = sprintf ("new Chart(%s, ", __chartjson__ (obj.chartID));
  ## Get Chart configuration json string
  json = jsonstring (obj);
  ## Close html string
  tmp8 = ");\n</script>";
  html = [tmp1, tag, tmp3, tmp4, tmp5, tmp6, tmp7, json, tmp8];
endfunction

